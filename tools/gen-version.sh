#!/bin/sh
# gen-version.sh — stamp VERSION into a Nim module, so the binary reports the version the
# repository declares instead of a literal somebody has to keep in step by hand.
#
#   gen-version.sh            (the repo root is derived from this script's own path)
#
# Deterministic on purpose: one constant, no timestamp, no commit, no absolute path. Two runs
# over the same VERSION produce a byte-identical module, which is what lets `./task
# version-check` compare instead of guess, and what makes a stale committed module a git diff.
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
out="$root/apps/api/src/generated/version.nim"

[ -f "$root/VERSION" ] || { echo "gen-version: no VERSION at $root/VERSION" >&2; exit 1; }
version=$(tr -d ' \n\r' <"$root/VERSION")

# Plain semver only: three numeric parts, nothing else. A range, a suffix or an empty file is a
# version no tag can carry, so it fails here rather than in a release tag.
case "$version" in
  '' | .* | *. | *..*)
    echo "gen-version: VERSION must be X.Y.Z (got '$version')" >&2
    exit 1
    ;;
esac
case "$version" in
  *[!0-9.]*)
    echo "gen-version: VERSION must be plain semver, digits and dots only (got '$version')" >&2
    exit 1
    ;;
esac
case "$version" in
  *.*.*) ;;
  *)
    echo "gen-version: VERSION must be X.Y.Z (got '$version')" >&2
    exit 1
    ;;
esac

[ -d "$(dirname "$out")" ] || mkdir -p "$(dirname "$out")"

tmp="$out.tmp"
{
  echo "# Generated by tools/gen-version.sh from VERSION. Do not edit, and do not hand-commit a change here."
  echo "# Regenerate: sh tools/gen-version.sh"
  echo ""
  echo "const KoriVersion* = \"$version\""
} >"$tmp"
mv "$tmp" "$out"

printf 'gen-version: %s stamped into %s\n' "$version" "${out#"$root"/}"
